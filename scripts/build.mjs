import { cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadContent } from './lib/content.mjs';
import { buildDirectory } from './lib/output.mjs';
import { render, escape } from '../src/render.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
if (args.length && (args.length !== 2 || args[0] !== '--out-dir')) {
  throw new Error('Usage: npm run build -- [--out-dir <directory>]');
}
const output = buildDirectory(root, args[1] || 'dist');

const content = await loadContent(root);
const marker = '.portfolio-build';
let previous;
try { previous = await readdir(output); } catch (error) { if (error.code !== 'ENOENT') throw error; }
if (previous?.length && !previous.includes(marker)) {
  throw new Error(`Refusing to replace an unrecognized directory: ${output}. Choose an empty build output directory.`);
}
// The resolved output was checked above; only an owned build directory is replaced.
await rm(output, { recursive: true, force: true });
await mkdir(resolve(output, 'assets'), { recursive: true });
await writeFile(resolve(output, marker), 'Generated by kevinsstuff/scripts/build.mjs\n');
const assets = {};
for (const [kind, file] of [['css', 'styles.css'], ['js', 'main.js']]) {
  const source = await readFile(resolve(root, 'src', file));
  const hash = createHash('sha256').update(source).digest('hex').slice(0, 10);
  const name = `${file.slice(0, file.lastIndexOf('.'))}.${hash}.${kind}`;
  await writeFile(resolve(output, 'assets', name), source);
  assets[kind] = `/assets/${name}`;
}
await cp(resolve(root, 'src', 'favicon.svg'), resolve(output, 'assets', 'favicon.svg'));
await cp(resolve(root, 'public'), output, { recursive: true });
await writeFile(resolve(output, 'index.html'), render(content, assets));
await writeFile(resolve(output, 'robots.txt'), `User-agent: *\nAllow: /\n${content.site.url ? `Sitemap: ${new URL('/sitemap.xml', content.site.url).href}\n` : ''}`);
if (content.site.url) {
  await writeFile(resolve(output, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"><url><loc>${escape(content.site.url)}</loc></url></urlset>\n`);
}
console.log(`Built ${content.projects.length} projects → ${output}`);
